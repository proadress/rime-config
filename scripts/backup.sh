#!/bin/sh
set -eu

repo_root=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
rime_dir=${RIME_DIR:-"$HOME/Library/Rime"}
target_dir="$repo_root/input-method/rime"

for name in default.custom.yaml squirrel.custom.yaml bopomofo_pro.schema.yaml; do
  source_file="$rime_dir/$name"
  if [ ! -f "$source_file" ]; then
    printf 'Missing required Rime file: %s\n' "$source_file" >&2
    exit 1
  fi
  cp "$source_file" "$target_dir/$name"
  printf 'Backed up %s\n' "$name"
done

maccy_settings="$repo_root/clipboard/maccy/settings.sh"
if defaults read org.p0deje.Maccy >/dev/null 2>&1; then
  history_size=$(defaults read org.p0deje.Maccy historySize 2>/dev/null || true)
  paste_by_default=$(defaults read org.p0deje.Maccy pasteByDefault 2>/dev/null || true)
  popup_shortcut=$(defaults read org.p0deje.Maccy KeyboardShortcuts_popup 2>/dev/null || true)

  if [ -n "$history_size" ] && [ -n "$paste_by_default" ] && [ -n "$popup_shortcut" ]; then
    {
      printf '%s\n' '# Maccy portable settings. Generated by scripts/backup.sh.'
      printf 'maccy_history_size=%s\n' "$history_size"
      printf 'maccy_paste_by_default=%s\n' "$paste_by_default"
      printf "maccy_popup_shortcut_json='%s'\n" "$popup_shortcut"
    } > "$maccy_settings"
    printf 'Backed up Maccy preferences.\n'
  else
    printf 'Skipped incomplete Maccy preferences.\n' >&2
  fi
else
  printf 'Maccy is not installed; skipped its preferences.\n'
fi

printf 'Clipboard contents were not collected.\n'
